"""FleetServer webfelület: telepítés, eltávolítás, Windows Update, csoportok, katalógus, szabályok. Adat: az e2e/Management után."""
import sys
from common import Run, browser
W=sys.argv[1] if len(sys.argv)>1 else "http://localhost:19380"
r=Run(); p,b=browser()
pg=r.page(b); r.login(pg,W,wait=".agent")
pg.fill("#search","könyv"); pg.wait_for_timeout(300)
r.chk("Keresés csoportnévre is szűr", pg.locator(".agent").count()==2, pg.locator(".agent").count())
pg.fill("#search",""); pg.locator(".agent", has_text="KONYV-1").first.click(); pg.wait_for_timeout(300)
r.chk("Windows Update táblázat", pg.locator(".wuchk").count()==2)
r.chk("Függő újraindítás és WSUS-forrás", pg.locator("#detail", has_text="újraindításra vár").count()==1 and pg.locator("#detail", has_text="WSUS").count()==1)
r.chk("Csoport-címke", pg.locator("#detail .badge", has_text="Könyvelés").count()==1)
pg.locator("#detail button", has_text="Program telepítése").click()
r.chk("Telepítés ablak: katalógus + alapcsomag", r.opens(pg,"Firefox") and pg.locator("#modalBody button", has_text="Teljes alapcsomag").count()==1)
pg.fill("#instId","VideoLAN.VLC"); pg.locator("#modalBody button.primary", has_text="Telepítés").click(); pg.wait_for_timeout(600)
r.chk("Szabad azonosítós telepítés kiadva", pg.locator("#toast", has_text="Telepítés").count()==1); r.close(pg)
pg.locator("#detail button", has_text="Program eltávolítása").click(); r.opens(pg,"HP Support")
r.chk("Eltávolítás: telepített programok", pg.locator(".unrow").count()==2)
pg.fill("#unFlt","hp"); pg.wait_for_timeout(200)
r.chk("Szűrés az eltávolítás listában", pg.locator(".unrow:visible").count()==1)
pg.locator(".unrow:visible button").click(); pg.wait_for_timeout(600)
r.chk("Eltávolítás kiadva", pg.locator("#toast", has_text="Eltávolítás").count()==1); r.close(pg)
pg.locator("#detail button", has_text="Kijelöltek telepítése").click(); pg.wait_for_timeout(600)
r.chk("Windows-frissítés kiadva", pg.locator("#toast", has_text="Windows-frissítés").count()==1)
pg.locator("#detail button", has_text="Újraindítás").click()
r.chk("Újraindítás ablak késleltetéssel", r.opens(pg,"Mikor") and pg.locator("#rbDelay").count()==1); r.close(pg)
pg.locator(".topbar .ghost", has_text="Csoportok").click()
r.chk("Csoportok: 2 csoport", r.opens(pg,"Szerverek") and pg.locator("#modalBody tr").count()==2); r.close(pg)
pg.locator(".topbar .ghost", has_text="Programok").click(); r.opens(pg,"Programkatalógus")
r.chk("Katalógus: 2 program", pg.locator("#modalBody input[data-f=id]").count()==2)
pg.locator("#modalBody button", has_text="Új sor").click()
r.chk("Új sor hozzáadható", pg.locator("#modalBody input[data-f=id]").count()==3); r.close(pg)
pg.locator(".topbar .ghost", has_text="Szabályok").click(); r.opens(pg,"Automatikus frissítési")
pg.locator("#modalBody button", has_text="Új szabály").click(); pg.wait_for_selector("#pName")
pg.fill("#pName","Éjszakai frissítés"); pg.locator("#modalBody button", has_text="Mentés").click()
r.chk("Szabály mentve a felületről", r.opens(pg,"Éjszakai frissítés"))
b.close(); p.stop(); r.finish()
